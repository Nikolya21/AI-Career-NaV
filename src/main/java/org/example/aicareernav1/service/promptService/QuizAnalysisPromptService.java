package org.example.aicareernav1.service.promptService;

import org.springframework.stereotype.Service;

@Service
public class QuizAnalysisPromptService {

    public String buildAnalysisPrompt(String vacancy, String userAnswersJson) {
        return String.format(
          "Ты — безжалостный технический аудит-бот. Твоя задача: проверить ответы кандидата на вакансию '%s'.\n\n" +
            "ВХОДНЫЕ ДАННЫЕ (JSON): %s\n\n" +
            "ИНСТРУКЦИЯ ПО ВАЛИДАЦИИ (КРИТИЧЕСКИ ВАЖНО):\n" +
            "1. ПРОВЕРКА НА МУСОР: Первым делом посмотри на текст ответа. Если там случайные буквы (типа 'asdf', 'jkbn'), " +
            "одиночные символы, ересь или ответ короче 5 символов — это 0 БАЛЛОВ. \n" +
            "2. ЗАПРЕТ ГАЛЛЮЦИНАЦИЙ: Тебе запрещено придумывать, что имел в виду кандидат. Если ответа по существу нет — " +
            "пиши 'ОТВЕТ ОТСУТСТВУЕТ ИЛИ ЯВЛЯЕТСЯ МУСОРОМ' и ставь 0/10.\n" +
            "3. ГРЕЙД 'NONE': Если у кандидата более 3-х мусорных ответов, его итоговый грейд — 'Некомпетентен (None)'.\n\n" +
            "СТРУКТУРА ОТЧЕТА:\n" +
            "## 1. Повопросный аудит\n" +
            "Для каждого вопроса:\n" +
            "- Текст ответа пользователя.\n" +
            "- Вердикт: (Корректен / Частичен / Мусор).\n" +
            "- Оценка: от 0 до 10.\n" +
            "- Критика: (Только если ответ осмысленный. Если мусор — просто пиши 'Игнорирование вопроса').\n\n" +
            "## 2. Итоговый грейд\n" +
            "Строго один вариант: None (мусор), Junior, Middle, Senior.\n\n" +
            "## 3. Вердикт 'Кто ты'\n" +
            "Если в ответах ересь, напиши прямо: 'Случайный бот или человек, саботирующий тест'.\n\n" +
            "## 4. Заключение\n" +
            "Честный профессиональный портрет. Если знаний ноль — так и пиши.\n\n" +
            "ПИШИ ТОЛЬКО ПО ФАКТУ ТОГО, ЧТО НАПИСАНО В ПОЛЕ ANSWER. Не оценивай свои вопросы!",
          vacancy, userAnswersJson
        );
    }
}