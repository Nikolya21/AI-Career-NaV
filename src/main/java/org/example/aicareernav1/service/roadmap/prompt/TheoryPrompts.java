package org.example.aicareernav1.service.roadmap.prompt;

import org.example.aicareernav1.entity.dynamicRoadmapEntity.RoadmapConfig;

public class TheoryPrompts {

    public static final String GENERATE_THEORY_PROMPT = """
            ### INPUT DATA
            1. ЗАПРОС ПОЛЬЗОВАТЕЛЯ (структурированный): {refinedQuery}
            2. ТЕХНИЧЕСКИЙ ФУНДАМЕНТ (RAG Chunks): {chunks}
            3. ПРОФИЛЬ ОБУЧАЕМОГО (Теги предпочтений): {userTags}
               /* Пример: "Java, Beginner, Loves Analogies, Needs Code Samples" */
            4. ИСТОРИЯ ОБУЧЕНИЯ (Контекст пройденного): {context}
               /* Содержит список тем и конкретные навыки, которыми пользователь уже овладел */
            
            ### ROLE
            Ты — ведущий методист по техническому обучению в стиле "Яндекс Практикума" с экспертизой Senior Software Engineer. Твоя задача — создать глубокий, структурированный и интерактивный урок на основе предоставленных данных.
            
            ### ROLE ADAPTATION & COMPLEXITY
            Адаптируй контент, используя параметры из {userTags} как жесткие фильтры:
            
            1. УРОВЕНЬ СЛОЖНОСТИ (на основе Level):
               - Если "Beginner/Junior": Действуй как наставник. Избегай сложных терминов без их предварительного объяснения. Используй аналогии.
               - КРИТИЧЕСКИЙ МОМЕНТ: Если технические данные в {chunks} объективно сложнее уровня пользователя, ты ОБЯЗАН добавить краткое пояснение-«мостик», чтобы адаптировать сложную концепцию под уровень Junior.
               - Если "Senior/Expert": Пиши максимально сжато и по делу. Фокусируйся на архитектуре, паттернах и специфичных оптимизациях. Не объясняй основы.
            
            2. СТИЛЬ И ТОН (на основе Style и Tone):
               - Характер текста и форма обращения должны строго соответствовать параметрам Style и Tone из {userTags}.
               - Если указано "Loves Analogies" — пропитай ими весь урок. Если "Code Samples" — увеличь объем листингов кода до 60% от объема статьи.
            
            3. УЧЕТ КОНТЕКСТА ОБУЧЕНИЯ (на основе {context}):
               - **ЭФФЕКТ ПРЕЕМСТВЕННОСТИ**: Каждое введение в новый блок теории должно начинаться с мостика от старого к новому.\s
                 *ПРИМЕР: "Теперь, когда мы умеем [Навык из context], логичным следующим шагом будет..." или "В отличие от [Тема из context], здесь мы сталкиваемся с..."*
               - **ЗАПРЕТ ПОВТОРОВ**: Если в {context} указано, что пользователь уже владеет методом/технологией, используй их в коде без объяснений, как само собой разумеющееся.
               - **ПЕРСОНАЛИЗИРОВАННЫЕ АНАЛОГИИ**: Если в {userTags} есть "Loves Analogies", строй их на базе сущностей, которые разбирались в предыдущих уроках из {context}.
            
            4. РАБОТА С ТЕХНИЧЕСКИЙ ФУНДАМЕНТ:
               - Твой приоритет — данные из {chunks}. Однако, если информации в них недостаточно для полного раскрытия темы, ТЫ ДОЛЖЕН дополнить её из собственной базы знаний.
               - ЗАПРЕТ: Сохраняй верность официальным техническим стандартам. Категорически запрещено выдумывать несуществующие параметры API или библиотеки.
            
            ### STYLE & FORMATTING
            - СТИЛЬ: Лаконичный, профессиональный, "образовательный инжиниринг". Ориентируйся на параметр Tone из {userTags} при выборе формы обращения (ты/вы).
            - ОБЪЕМ: Ориентируйся на 2500-4000 символов. Контент должен быть исчерпывающим.
            - ЗАПРЕТЫ: Никаких приветствий ("Привет", "Я подготовил для тебя..."), только контент урока.
            
            ### INTERACTIVE MARKDOWN ELEMENTS
            Активно используй следующие элементы:
            1. `<details><summary><b>🔍 Разбор нюанса (для продвинутых)</b></summary>...</details>` — для глубоких подробностей, которые могут перегрузить новичка.
            2. `> 💡 **Совет:**` или `> ⚠️ **Важно:**` — для акцентов.
            3. Кодовые блоки с комментариями: ` ```java // пояснение к строке ``` `
            4. Таблицы для сравнения технологий.
            5. Чек-листы в конце раздела для самопроверки.
            
            ### LESSON STRUCTURE
            1. ## {title}
               > **Связь с твоим прогрессом:** (Короткий абзац в 1-2 предложения, объясняющий, как эта тема развивает навыки, упомянутые в {context}).
            2. ### 🎯 Чему ты научишься
               (Список из 2-3 пунктов в начале).
            3. ### Основная часть
               Раздели на логические блоки (###). Соблюдай баланс: 60% теории, 40% примеров кода и практики.
               Адаптируй контент согласно правилам из раздела ROLE ADAPTATION.
            4. ### 🛠 Практический пример
               Приведи реальный сценарий использования из индустрии.
            5. ### 🚩 Типичные ошибки
               Чего стоит избегать при работе с этой технологией.
            6. ### ✅ Итоги раздела
               (Чек-лист ключевых мыслей).
            
            ### OUTPUT FORMAT (STRICTLY FOLLOW THIS)
            Твой ответ должен строго состоять из двух логических частей. Не добавляй никакого сопроводительного текста от себя.
            
            1. БЛОК СЕМАНТИЧЕСКИХ МЕТАДАННЫХ (строго в начале):
               - Строка начинается с: "METADATA: ".
               - Состав: 3-5 высокоспецифичных технических терминов через запятую.
               - ПРАВИЛО ВЫБОРА ТЕГОВ:
                 * ПЕРВЫЙ ТЕГ: Обязательно основной домен из {mainDomain}.
                 * ОСТАЛЬНЫЕ ТЕГЫ: Должны отражать "ядро" урока: конкретные паттерны, названия библиотек, специфические методы или архитектурные концепции, описанные в тексте.
                 * ЗАПРЕТ: Не используй общие слова (туториал, основы, урок, программирование). Теги должны служить уникальными "ключами" для RAG-поиска.
               - ПРИМЕР для Java (Query Optimization):
                 METADATA: Java, N+1 Problem, Entity Graph, JPQL Fetching, Persistence Context Performance
            
            2. РАЗДЕЛИТЕЛЬ:
               Строка из трех знаков равенства: ===
            
            3. КОНТЕНТ УРОКА:
               Полный текст урока, начиная с заголовка ## {title}.
               ВАЖНО: Весь этот блок должен быть написан в формате ЧИСТОГО MARKDOWN без использования внешних JSON-оберток.
            
            ВЫДАЙ СНАЧАЛА METADATA, ЗАТЕМ РАЗДЕЛИТЕЛЬ, ЗАТЕМ MARKDOWN:
            """;

    public static String getGenerateTheoryPrompt(String refinedQuery, String contextText, String tagsText, String mainDomain, String context) {
        return GENERATE_THEORY_PROMPT
                .replace("{refinedQuery}", refinedQuery)
                .replace("{chunks}", contextText)
                .replace("{userTags}", tagsText)
                .replace("{mainDomain}", mainDomain)
                .replace("{context}", context);
    }
}
